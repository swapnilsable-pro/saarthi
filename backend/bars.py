"""Bar store: intraday 5-minute charts saved exactly as the repo's own fetcher returned them.

Yahoo throttles by IP for hours after about a dozen calls (nse-trader-skill README), and the
Time Machine needs one 60-session chart per symbol, while an idea runs it ~25 times (plan
variants and the timing curve). So each chart is fetched ONCE through nse-trader-skill's own
nsedata.yahoo_get and saved under data/bars/<day>/. Every tool then reads it through its
documented --offline flag. Saarthi never parses prices for decisions; it only stores the
file and, for drawing the chart, reads it back with the repo's nsedata.series_from_chart.

Demo mode points at a folder assembled from the repo's own test fixtures.
"""
from __future__ import annotations

import datetime as dt
import shutil
import time
from pathlib import Path

from backend import clock  # noqa: F401  (puts nse-common on sys.path)
from backend.skills.registry import ROOT

import nsedata  # noqa: E402  (vendored, unmodified)
import nsecal   # noqa: E402

BARS = ROOT / "data" / "bars"
DEMO_DIR = ROOT / "data" / "demo" / "intraday"
NSE_FX = ROOT / "vendor/nse-trader-skill/tests/fixtures"
REFRESH_S = 240          # live: refetch a symbol's chart at most every 4 minutes during a session


def _name(sym: str, rng: str) -> str:
    return "chart-%s-%s-5m.json" % (nsedata.to_yahoo(sym).replace("^", "idx-"), rng)


def demo_dir() -> Path:
    """Fixture-backed intraday folder. DEMO is the nse repo's synthetic test instrument (60 sessions,
    ending Mon 9 Nov 2026); TCS is its real-data 1-day fixture for the same session."""
    DEMO_DIR.mkdir(parents=True, exist_ok=True)
    src_demo = NSE_FX / "nse-timemachine" / "chart-DEMO.NS-60d-5m.json"
    for target in (_name("DEMO", "60d"), _name("DEMO", "1d")):
        if not (DEMO_DIR / target).exists():
            shutil.copyfile(src_demo, DEMO_DIR / target)
    tcs = NSE_FX / "nse-scanner" / "chart-TCS.NS-1d-5m.json"
    if not (DEMO_DIR / _name("TCS", "1d")).exists():
        shutil.copyfile(tcs, DEMO_DIR / _name("TCS", "1d"))
    return DEMO_DIR


DEMO_SYMBOLS = ["DEMO", "TCS"]
SYNTHETIC = {"DEMO"}     # generated by nse-trader-skill tools/make_fixture.py; no listed company behind it


def live_dir(day: dt.date) -> Path:
    d = BARS / day.isoformat()
    d.mkdir(parents=True, exist_ok=True)
    return d


def ensure_live(sym: str, day: dt.date, *, force: bool = False) -> Path:
    """Fetch (or reuse) the 60-session 5-minute chart for sym via nse-trader-skill's fetcher."""
    d = live_dir(day)
    p60 = d / _name(sym, "60d")
    fresh = p60.exists() and (time.time() - p60.stat().st_mtime) < REFRESH_S
    session_over = day < clock.ist_now().date()
    if p60.exists() and (fresh or session_over) and not force:
        return d
    text = nsedata.yahoo_get(nsedata.chart_path(sym, "60d", "5m"))
    p60.write_text(text)
    shutil.copyfile(p60, d / _name(sym, "1d"))     # scan.py orb --offline reads the -1d- name
    return d


def bars_dir(mode: str, day: dt.date) -> Path:
    return demo_dir() if mode == "demo" else live_dir(day)


def history_dir(mode: str, sym: str, day: dt.date) -> Path | None:
    """A folder whose saved chart for `sym` covers `day`: that day's own folder, else the nearest later
    live folder (a 60-session chart fetched on day X contains the 59 sessions before X)."""
    if mode == "demo":
        return demo_dir()
    own = BARS / day.isoformat()
    if (own / _name(sym, "60d")).exists() or (own / _name(sym, "1d")).exists():
        return own
    if BARS.exists():
        for d in sorted(p for p in BARS.iterdir() if p.is_dir() and p.name >= day.isoformat()):
            if (d / _name(sym, "60d")).exists():
                return d
    return None


def session_days(mode: str, sym: str, folder: Path | None = None) -> list[dt.date]:
    """Every session day contained in the saved 60-session chart for sym."""
    folder = folder or (demo_dir() if mode == "demo" else None)
    path = folder / _name(sym, "60d") if folder else None
    if not path or not path.exists():
        return []
    ser = nsedata.series_from_chart(path.read_text())
    return sorted({nsecal.to_ist(nsecal.utc_of(t)).date() for t in ser["t"]})


def session_bars(mode: str, sym: str, day: dt.date, until: dt.datetime | None = None) -> list[dict]:
    """Bars of one session for the chart, oldest first, cut at `until` (no look-ahead)."""
    folder = history_dir(mode, sym, day)
    if folder is None:
        return []
    path = folder / _name(sym, "60d")
    if not path.exists():
        path = folder / _name(sym, "1d")
    if not path.exists():
        return []
    ser = nsedata.series_from_chart(path.read_text())
    out = []
    for i, ts in enumerate(ser["t"]):
        local = nsecal.to_ist(nsecal.utc_of(ts))
        if local.date() != day or ser["c"][i] is None:
            continue
        if until and local + dt.timedelta(minutes=5) > until:
            continue
        out.append({"time": local.strftime("%Y-%m-%d %H:%M"), "o": ser["o"][i], "h": ser["h"][i],
                    "l": ser["l"][i], "c": ser["c"][i], "v": ser["v"][i]})
    return out
